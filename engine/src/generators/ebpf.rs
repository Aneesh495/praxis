// Praxis Execution Engine
// Generators: eBPF XDP C Kernel Source Generator

pub struct EbpfGenerator;

impl EbpfGenerator {
    pub fn new() -> Self {
        Self
    }

    pub fn generate_xdp_source(&self, rules: &[(&str, &str, u16, &str)], default_action: &str) -> String {
        let mut rule_checks = Vec::new();

        for (name, proto, port, action) in rules {
            let proto_num = if *proto == "udp" { 17 } else { 6 };
            rule_checks.push(format!(
                r#"    // Rule: {}
    if (ip->protocol == {} && l4_port == {}) {{
        return {};
    }}"#,
                name, proto_num, port, action
            ));
        }

        format!(
            r#"// Auto-generated by Praxis eBPF Synthesizer
#include <linux/bpf.h>
#include <linux/if_ether.h>
#include <linux/ip.h>
#include <linux/tcp.h>
#include <linux/udp.h>
#include <bpf/bpf_helpers.h>

SEC("xdp")
int xdp_firewall_prog(struct xdp_md *ctx) {{
    void *data = (void *)(long)ctx->data;
    void *data_end = (void *)(long)ctx->data_end;

    struct ethhdr *eth = data;
    if ((void *)(eth + 1) > data_end)
        return XDP_DROP;

    if (eth->h_proto != __constant_htons(ETH_P_IP))
        return XDP_PASS;

    struct iphdr *ip = (void *)(eth + 1);
    if ((void *)(ip + 1) > data_end)
        return XDP_DROP;

    __u16 l4_port = 0;
    if (ip->protocol == IPPROTO_TCP) {{
        struct tcphdr *tcp = (void *)ip + (ip->ihl * 4);
        if ((void *)(tcp + 1) > data_end)
            return XDP_DROP;
        l4_port = __constant_ntohs(tcp->dest);
    }} else if (ip->protocol == IPPROTO_UDP) {{
        struct udphdr *udp = (void *)ip + (ip->ihl * 4);
        if ((void *)(udp + 1) > data_end)
            return XDP_DROP;
        l4_port = __constant_ntohs(udp->dest);
    }}

{}

    return {};
}}

char _license[] SEC("license") = "GPL";
"#,
            rule_checks.join("\n\n"),
            default_action
        )
    }
}
